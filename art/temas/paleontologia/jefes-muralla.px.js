const runSprite = (name, w, h, rows) => sprite(name, { w, h }, (c) => {
  rows.forEach((row, y) => {
    let x = 0;
    for (let i = 0; i < row.length; i += 2) {
      const key = row[i], n = countChars.indexOf(row[i + 1]) + 1;
      if (key !== ".") c.rect(x, y, n, 1, key);
      x += n;
    }
  });
});


