const S = 16;
const NAMES = [];

// Dibujo en una rejilla libre ('#' tinta); se centra solo por su caja en el lienzo de 16×16.
// mx: refleja cada fila a la derecha; my: refleja las filas hacia abajo; dx/dy: ajuste óptico.
function icon(name, src, o = {}) {
  let rows = Array.isArray(src) ? src : src.split("\n").map((s) => s.trim()).filter(Boolean);
  if (o.mx) rows = rows.map((r) => r + [...r].reverse().join(""));
  if (o.my) rows = [...rows, ...rows.slice().reverse()];
  const pts = [];
  rows.forEach((r, y) => [...r].forEach((ch, x) => ch === "#" && pts.push([x, y])));
  place(name, pts, o);
}

// Igual, pero dibujado con código sobre un búfer (líneas gruesas, círculos por distancia).
function drawn(name, fn, o = {}) {
  const N = 32, buf = new Map();
  const set = (x, y, v = 1) => { x = Math.round(x); y = Math.round(y); if (v) buf.set(x + "," + y, 1); else buf.delete(x + "," + y); };
  const api = {
    set,
    // disco por distancia al centro de píxel; cx,cy en coordenadas de borde (8 = entre 7 y 8)
    disc(cx, cy, r, v = 1, r0 = -1) {
      for (let y = Math.floor(cy - r - 1); y <= cy + r + 1; y++)
        for (let x = Math.floor(cx - r - 1); x <= cx + r + 1; x++) {
          const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
          if (d <= r && d > r0) set(x, y, v);
        }
    },
    rect(x, y, w, h, v = 1) { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) set(x + i, y + j, v); },
    // trazo grueso: cuadrado de w×w a lo largo del segmento
    line(x0, y0, x1, y1, w = 2, v = 1) {
      const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) * 2 + 1;
      for (let i = 0; i <= n; i++) {
        const x = x0 + ((x1 - x0) * i) / n, y = y0 + ((y1 - y0) * i) / n;
        for (let a = 0; a < w; a++) for (let b = 0; b < w; b++) set(Math.floor(x) + a, Math.floor(y) + b, v);
      }
    },
    poly(p, v = 1) {
      const xs = p.filter((_, i) => i % 2 === 0), ys = p.filter((_, i) => i % 2);
      for (let y = Math.floor(Math.min(...ys)); y <= Math.max(...ys); y++)
        for (let x = Math.floor(Math.min(...xs)); x <= Math.max(...xs); x++) {
          const px = x + 0.5, py = y + 0.5;
          let inside = false;
          for (let i = 0, j = xs.length - 1; i < xs.length; j = i++)
            if ((ys[i] > py) !== (ys[j] > py) && px < ((xs[j] - xs[i]) * (py - ys[i])) / (ys[j] - ys[i]) + xs[i]) inside = !inside;
          if (inside) set(x, y, v);
        }
    },
    has: (x, y) => buf.has(x + "," + y),
  };
  fn(api);
  place(name, [...buf.keys()].map((k) => k.split(",").map(Number)), o);
}

function place(name, pts, o) {
  const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  const x0 = Math.min(...xs), y0 = Math.min(...ys), w = Math.max(...xs) - x0 + 1, h = Math.max(...ys) - y0 + 1;
  if (w > 14 || h > 14) throw new Error(`${name}: ${w}×${h} se sale del margen de 14×14`);
  const ox = Math.floor((S - w) / 2) + (o.dx || 0) - x0, oy = Math.floor((S - h) / 2) + (o.dy || 0) - y0;
  NAMES.push(name);
  sprite(name, { w: S, h: S }, (c) => pts.forEach(([x, y]) => c.px(x + ox, y + oy, "k")));
}

