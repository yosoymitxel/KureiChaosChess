// Ficha de damas de canto: cara de arriba con su surco, canto grueso debajo.
drawn("checkers", (g) => {
  const E = (x, y, cx, cy, rx, ry) => ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2;
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const top = E(x, y, 8, 6, 7, 3.6), bot = E(x, y, 8, 10, 7, 3.6);
    const side = x >= 1 && x < 15 && y + 0.5 >= 6 && y + 0.5 <= 10;
    if (top <= 1 || bot <= 1 || side) g.set(x, y);
    const groove = E(x, y, 8, 6, 4.2, 1.9);
    if (groove <= 1 && groove > 0.45) g.set(x, y, 0);
    const lip = E(x, y, 8, 6.9, 7, 3.6);                       // junta entre cara y canto
    if (y + 0.5 > 6.5 && lip > 0.98 && lip <= 1.45 && top > 1) g.set(x, y, 0);
  }
});

